// ---------- helpers ----------
export function getCharacter(id) {
  return CHARACTERS.find((c) => c.id === id);
}

// Add one character by id: addCharacter(cast, makeLook, rand, "captain", 100, [-2, 1])
export function addCharacter(cast, makeLook, rand, id, seed, pos = [0, 0]) {
  const def = typeof id === "string" ? getCharacter(id) : id;
  if (!def) throw new Error("Unknown character: " + id);
  const c = cast.add({
    name: def.id,
    look: makeLook(rand.fork(seed), def.role, def.look),
    pos, h: def.h, face: def.face,
  });
  c.arms(0, def.arms);
  return c;
}

// Add all 52 at once (seeds 100..151). Returns the array of cast members.
export function addAll(cast, makeLook, rand, fromSeed = 100) {
  return CHARACTERS.map((def, i) => addCharacter(cast, makeLook, rand, def, fromSeed + i));
}
